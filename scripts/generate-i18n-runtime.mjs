import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const config = JSON.parse(fs.readFileSync(path.join(rootDir, "i18n", "config.json"), "utf8"));
const outputPath = path.join(rootDir, "src", "i18n", "runtimeConfig.ts");
const translationsPath = path.join(rootDir, "src", "i18n", "runtimeTranslations.ts");
const labels = Object.fromEntries(config.runtimeLocales.map((locale) => [locale, config.localeLabels[locale] ?? locale]));
const aliases = Object.fromEntries(Object.entries(config.localeAliases ?? {}).filter(([, locale]) => config.runtimeLocales.includes(locale)));
const output = `// Generated by scripts/generate-i18n-runtime.mjs. Edit i18n/config.json instead.\n` +
  `export const RUNTIME_LOCALES = ${JSON.stringify(config.runtimeLocales)} as const;\n` +
  `export const RUNTIME_LOCALE_LABELS: Record<string, string> = ${JSON.stringify(labels, null, 2)};\n` +
  `export const RUNTIME_LOCALE_ALIASES: Record<string, string> = ${JSON.stringify(aliases, null, 2)};\n` +
  `export const RUNTIME_RTL_LOCALES = ${JSON.stringify((config.rtlLocales ?? []).filter((locale) => config.runtimeLocales.includes(locale)))} as const;\n`;
fs.writeFileSync(outputPath, output, "utf8");
const translations = {};
for (const locale of config.runtimeLocales) {
  if (locale === "en" || locale === "ja") continue;
  const validatedPath = path.join(rootDir, "i18n", "translations", `${locale}.json`);
  const batchPath = path.join(rootDir, "i18n", "app-batches", `${locale}-core.json`);
  if (fs.existsSync(validatedPath)) {
    const catalog = JSON.parse(fs.readFileSync(validatedPath, "utf8"));
    translations[locale] = Object.fromEntries(Object.entries(catalog).filter(([id]) => !id.startsWith("page.")));
  } else if (fs.existsSync(batchPath)) {
    const batch = JSON.parse(fs.readFileSync(batchPath, "utf8"));
    const aiBatchPath = path.join(rootDir, "i18n", "app-batches", `${locale}-ai-cloud-editor.json`);
    const aiBatch = fs.existsSync(aiBatchPath) ? JSON.parse(fs.readFileSync(aiBatchPath, "utf8")) : null;
    translations[locale] = { ...batch.messages, ...(aiBatch?.messages ?? {}) };
  } else {
    throw new Error(`${locale}: runtime locale has no translation batch or validated translation file.`);
  }
}
fs.writeFileSync(translationsPath, `// Generated by scripts/generate-i18n-runtime.mjs. Edit i18n/translations/*.json instead.\nexport const RUNTIME_TRANSLATIONS: Record<string, Record<string, string>> = ${JSON.stringify(translations, null, 2)};\n`, "utf8");
console.log(`Generated ${path.relative(rootDir, outputPath)}`);
